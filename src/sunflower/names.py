def en_id(s):
    s = str(s)
    if s in VALUES:
        return VALUES[s]
    if not _CYR.search(s):
        return s
    for p, r in _ID:
        s = p.sub(r, s)
    return s


def ru_id(s):
    s = str(s)
    if s in _RU_VAL:
        return _RU_VAL[s]
    for p, r in _RID:
        s = p.sub(r, s)
    return s


